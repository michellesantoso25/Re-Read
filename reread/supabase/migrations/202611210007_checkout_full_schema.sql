-- older marketplace tables already present in the linked Supabase project.

alter table public.books
  add column if not exists seller_id uuid references auth.users(id) on delete set null;
grant select on table public.books to service_role;
grant usage on schema public to service_role;

alter table public.orders
  add column if not exists buyer_id uuid references auth.users(id) on delete restrict,
  add column if not exists midtrans_order_id text,
  add column if not exists status text not null default 'pending',
  add column if not exists payment_status text not null default 'pending',
  add column if not exists subtotal bigint not null default 0,
  add column if not exists shipping_total bigint not null default 0,
  add column if not exists discount bigint not null default 0,
  add column if not exists platform_subsidy bigint not null default 0,
  add column if not exists gross_amount bigint not null default 1,
  add column if not exists voucher_code text,
  add column if not exists delivery_address jsonb not null default '{}'::jsonb,
  add column if not exists snap_token text,
  add column if not exists redirect_url text,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists paid_at timestamptz;

create unique index if not exists orders_midtrans_order_id_uidx
  on public.orders(midtrans_order_id)
  where midtrans_order_id is not null;

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  book_id text not null,
  seller_id uuid not null references auth.users(id) on delete restrict,
  title text not null,
  unit_price bigint not null check (unit_price >= 0),
  created_at timestamptz not null default now()
);

alter table public.order_items
  add column if not exists order_id uuid references public.orders(id) on delete cascade,
  add column if not exists book_id text,
  add column if not exists seller_id uuid references auth.users(id) on delete restrict,
  add column if not exists title text,
  add column if not exists unit_price bigint,
  add column if not exists created_at timestamptz not null default now();

create table if not exists public.seller_wallet_ledger (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete restrict,
  seller_id uuid not null references auth.users(id) on delete restrict,
  amount bigint not null check (amount >= 0),
  created_at timestamptz not null default now(),
  unique (order_id, seller_id)
);

alter table public.seller_wallet_ledger
  add column if not exists order_id uuid references public.orders(id) on delete restrict,
  add column if not exists seller_id uuid references auth.users(id) on delete restrict,
  add column if not exists amount bigint,
  add column if not exists created_at timestamptz not null default now();

-- Required to make repeated settlement notifications idempotent per seller/order.
create unique index if not exists seller_wallet_ledger_order_seller_idempotency_uidx
  on public.seller_wallet_ledger(order_id, seller_id);

create unique index if not exists seller_wallet_ledger_order_seller_uidx
  on public.seller_wallet_ledger(order_id, seller_id)
  where order_id is not null and seller_id is not null;

alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.seller_wallet_ledger enable row level security;

drop policy if exists "Buyers can read their orders" on public.orders;
create policy "Buyers can read their orders" on public.orders
  for select to authenticated using (buyer_id = auth.uid());
drop policy if exists "Buyers can read their order items" on public.order_items;
create policy "Buyers can read their order items" on public.order_items
  for select to authenticated using (
    exists (select 1 from public.orders o where o.id = order_id and o.buyer_id = auth.uid())
  );
drop policy if exists "Sellers can read their wallet ledger" on public.seller_wallet_ledger;
create policy "Sellers can read their wallet ledger" on public.seller_wallet_ledger
  for select to authenticated using (seller_id = auth.uid());

grant select, insert, update on table public.orders to service_role;
grant select, insert on table public.order_items to service_role;
grant select, insert on table public.seller_wallet_ledger to service_role;

create or replace function public.record_midtrans_notification(
  p_midtrans_order_id text,
  p_gross_amount bigint,
  p_transaction_status text,
  p_paid boolean
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
begin
  select * into v_order
  from public.orders
  where midtrans_order_id = p_midtrans_order_id
  for update;

  if not found then raise exception 'Order not found'; end if;
  if p_gross_amount <> v_order.gross_amount then
    raise exception 'Notification amount does not match order';
  end if;

  if p_paid then
    if v_order.payment_status <> 'paid' then
      insert into public.seller_wallet_ledger(order_id, seller_id, amount)
      select oi.order_id, oi.seller_id, sum(oi.unit_price)
      from public.order_items oi
      where oi.order_id = v_order.id
      group by oi.order_id, oi.seller_id
      on conflict (order_id, seller_id) do nothing;

      update public.orders
      set status = 'paid', payment_status = 'paid', paid_at = now()
      where id = v_order.id;
    end if;
  elsif p_transaction_status in ('expire', 'cancel', 'deny')
    and v_order.payment_status <> 'paid' then
    update public.orders
    set status = p_transaction_status, payment_status = p_transaction_status
    where id = v_order.id;
  end if;
end;
$$;

revoke all on function public.record_midtrans_notification(text, bigint, text, boolean)
  from public, anon, authenticated;
grant execute on function public.record_midtrans_notification(text, bigint, text, boolean)
  to service_role;

notify pgrst, 'reload schema';
